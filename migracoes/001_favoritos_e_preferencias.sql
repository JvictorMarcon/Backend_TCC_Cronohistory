-- Eventos favoritados por cada usuário.
-- evento_chave = nome do evento sem acento e em minúsculas (ex.: 'queda de constantinopla').
-- Usa o NOME (e não o id) porque o mesmo evento aparece na linha do tempo, na
-- galeria e no periodos.json com ids diferentes, mas sempre com o mesmo nome.
CREATE TABLE IF NOT EXISTS public.favoritos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES public.usuario(id) ON DELETE CASCADE,
    evento_chave TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (usuario_id, evento_chave)
);
CREATE INDEX IF NOT EXISTS idx_favoritos_usuario ON public.favoritos(usuario_id);

-- Preferências do site de cada usuário (tamanho da fonte, tema, etc.),
-- para acompanhar a pessoa em qualquer computador/celular.
CREATE TABLE IF NOT EXISTS public.preferencias (
    usuario_id BIGINT PRIMARY KEY REFERENCES public.usuario(id) ON DELETE CASCADE,
    dados JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
